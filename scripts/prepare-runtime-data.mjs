import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const datasets = [
  ['lexicon/it.json', 'lexicon.js'],
  ['context/it-context.json', 'context.js'],
  ['context/it-openings.json', 'openings.js'],
  ['probability/it-model.json', 'probability.js'],
];
await mkdir(new URL('assets/runtime/', root), { recursive: true });
for (const [source, output] of datasets) {
  const raw = await readFile(new URL(`assets/${source}`, root), 'utf8');
  JSON.parse(raw); // Reject invalid data at build time, before it reaches a phone.
  const code = `// Generated by scripts/prepare-runtime-data.mjs; edit the source JSON instead.\n// Parse data at runtime instead of compiling hundreds of thousands of nested array literals.\nmodule.exports = JSON.parse(${JSON.stringify(raw)});\n`;
  const destination = new URL(`assets/runtime/${output}`, root);
  const existing = await readFile(destination, 'utf8').catch(() => '');
  if (existing !== code) await writeFile(destination, code);
  console.log(`Runtime data ready: ${fileURLToPath(destination)}`);
}
